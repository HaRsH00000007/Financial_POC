def framework() -> dict:
    return {
        "dimensions": [
            {"key": k, "name": n, "description": d, "guiding_questions": q, "suggested_tests": t, "default_weight": 1}
            for k, n, d, q, t in DIMENSIONS
        ],
        "scale": ASSESSMENT_SCALE,
        "evidence_types": EVIDENCE_TYPES,
        "disclaimer": "Assessments are entered by the evaluator from evidence they collected. The aggregate index "
                      "is a transparent weighted average of those assessments, not an industry benchmark or a "
                      "scientifically validated score.",
    }


def weighted_index(scores: list[tuple[float, float]]) -> float | None:
    """sum(w*s) / sum(w*4) over assessed dimensions, via the deterministic evaluator."""
    if not scores:
        return None
    names = {}
    num_terms, den_terms = [], []
    for i, (w, s) in enumerate(scores):
        names[f"w{i}"], names[f"s{i}"] = w, s
        num_terms.append(f"w{i} * s{i}")
        den_terms.append(f"w{i} * 4")
    result, _, undefined = evaluate(f"({' + '.join(num_terms)}) / ({' + '.join(den_terms)})", names)
    return None if result is None or undefined else float(round(result, 4))


def summarize(evaluation: dict) -> dict:
    dims = {d["key"]: d for d in framework()["dimensions"]}
    weights = {k: float(evaluation.get("weights", {}).get(k, 1)) for k in dims}
    platforms = evaluation.get("platforms", [])
    cells = evaluation.get("cells", {})
    out = []
    for p in platforms:
        pid = p["id"]
        scores, assessed, evidence_count, strengths, limitations = [], 0, 0, [], []
        for k in dims:
            cell = cells.get(f"{pid}:{k}", {})
            s = SCALE_BY_KEY.get(cell.get("assessment", "not_assessed"), SCALE_BY_KEY["not_assessed"])["score"]
            entries = cell.get("entries", [])
            evidence_count += len(entries)
            if s is not None:
                assessed += 1
                scores.append((weights[k], s))
                if s >= 3:
                    strengths.append(dims[k]["name"])
                if s <= 1:
                    limitations.append(dims[k]["name"])
            limitations += [f"{dims[k]['name']}: {e.get('text', '')}" for e in entries if e.get("type") == "limitation"]
        out.append({
            "platform_id": pid, "name": p["name"], "assessed": assessed, "of": len(dims),
            "coverage": round(assessed / len(dims), 4), "evidence_items": evidence_count,
            "index": weighted_index(scores), "strengths": strengths, "limitations": limitations,
            "unsupported_claims": sum(
                1 for k in dims for e in cells.get(f"{pid}:{k}", {}).get("entries", [])
                if e.get("type") == "vendor_claim" and not any(
                    x.get("type") in ("test_result", "evidence") for x in cells.get(f"{pid}:{k}", {}).get("entries", [])))
        })
    return {"platforms": out, "method": "index = sum(weight x score) / sum(weight x 4) over assessed dimensions; "
                                         "unassessed dimensions are excluded, not scored as zero."}


def report_markdown(evaluation: dict) -> str:
    fw = framework()
    dims = fw["dimensions"]
    summary = summarize(evaluation)
    cells = evaluation.get("cells", {})
    scale = {s["key"]: s["label"] for s in ASSESSMENT_SCALE}
    ev_label = {e["key"]: e["label"] for e in EVIDENCE_TYPES}
    title = evaluation.get("title") or "Enterprise AI Accounting Platform Evaluation"
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [f"# {title}", "", f"_Generated {now} by Finance Intelligence Workbench_", ""]
    if evaluation.get("is_example"):
        lines += ["> **ILLUSTRATIVE EXAMPLE** - fictional platforms and evidence for demonstration only.", ""]
    lines += [f"> {fw['disclaimer']}", "", "## Summary", "",
              "| Platform | Assessed | Evidence items | Weighted index | Vendor claims without tests |",
              "|---|---|---|---|---|"]
    for p in summary["platforms"]:
        idx = "n/a" if p["index"] is None else f"{p['index'] * 100:.0f} / 100"
        lines.append(f"| {p['name']} | {p['assessed']}/{p['of']} | {p['evidence_items']} | {idx} | {p['unsupported_claims']} |")
    lines += ["", f"_Method: {summary['method']}_", ""]
    for p in summary["platforms"]:
        lines += [f"### {p['name']}", "",
                  "**Strengths:** " + (", ".join(p["strengths"]) or "none recorded"), "",
                  "**Limitations:** " + ("; ".join(p["limitations"]) or "none recorded"), ""]
    lines += ["## Detailed assessment", ""]
    for d in dims:
        lines += [f"### {d['name']}", "", f"_{d['description']}_", ""]
        for p in evaluation.get("platforms", []):
            cell = cells.get(f"{p['id']}:{d['key']}", {})
            lines.append(f"- **{p['name']}** - {scale.get(cell.get('assessment', 'not_assessed'))}")
            for e in cell.get("entries", []):
                src = f" _(source: {e['source']})_" if e.get("source") else ""
                lines.append(f"  - {ev_label.get(e.get('type'), 'Note')}: {e.get('text', '')}{src}")
        lines.append("")
    return "\n".join(lines)
